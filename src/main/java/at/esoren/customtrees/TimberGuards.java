package at.esoren.customtrees;

import Vystorm.vystorm_core.region.Region;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import org.bukkit.entity.Entity;

/** Small rules of the timber: concurrency caps, Core region rules, origin checks and display cleanup. */
final class TimberGuards {
    private TimberGuards() {}

    /** Scoreboard tag of every timber display entity (also non-persistent, so a crash never saves them). */
    static final String DISPLAY_TAG = "customtrees_timber";

    /** Concurrent fells per world and per player. Server thread. */
    static final class Limits {
        private final Map<UUID, Integer> worlds = new HashMap<>();
        private final Map<UUID, Integer> players = new HashMap<>();

        boolean tryAcquire(UUID world, UUID player, int perWorld, int perPlayer) {
            if (worlds.getOrDefault(world, 0) >= perWorld || players.getOrDefault(player, 0) >= perPlayer) return false;
            worlds.merge(world, 1, Integer::sum);
            players.merge(player, 1, Integer::sum);
            return true;
        }

        void release(UUID world, UUID player) {
            worlds.computeIfPresent(world, (key, count) -> count <= 1 ? null : count - 1);
            players.computeIfPresent(player, (key, count) -> count <= 1 ? null : count - 1);
        }

        int active() { return worlds.values().stream().mapToInt(Integer::intValue).sum(); }

        void clear() { worlds.clear(); players.clear(); }
    }

    /**
     * Whether Core regions forbid the timber at a block. The regions containing the block are checked from the highest
     * priority down: an explicit {@code timber} flag decides; otherwise a region of a protected kind (spawn, arena,
     * market, dungeon, structure, ...) refuses. Cities and territories are left to their own plugin, which sees the
     * {@link TimberBreakEvent}.
     */
    static boolean regionDenies(List<Region> containing, List<String> protectedKinds) {
        if (containing.isEmpty()) return false;
        List<Region> sorted = containing.stream().sorted(Comparator.comparingInt(Region::priority).reversed()).toList();
        for (Region region : sorted) {
            var flag = region.flag("timber");
            if (flag.isPresent()) return !flag.get();
        }
        for (Region region : sorted) if (protectedKinds.contains(region.kind())) return true;
        return false;
    }

    /** What CoreProtect knows about the trunk: placed by a player, nothing (natural) or no answer. */
    enum History { PLAYER_PLACED, NATURAL, UNKNOWN }

    /**
     * Final decision on a scanned tree: logs a player placed are never felled (when the check is on); with
     * {@code only-generated-trees} the tree must be grown or generated by CustomTrees (marked blocks) or confirmed
     * natural by CoreProtect.
     */
    static boolean originAccepted(int markedBlocks, History history, boolean coreProtectCheck, boolean onlyGenerated) {
        if (coreProtectCheck && history == History.PLAYER_PLACED && markedBlocks == 0) return false;
        if (!onlyGenerated) return true;
        return markedBlocks > 0 || history == History.NATURAL;
    }

    /** Whether a CoreProtect user name is a real player (not "#tree", "#decay" or CustomTrees itself). */
    static boolean playerUser(String user) {
        return user != null && !user.isBlank() && !user.startsWith("#") && !user.equalsIgnoreCase("CustomTrees");
    }

    static boolean isTimberDisplay(Entity entity) {
        return entity != null && entity.getScoreboardTags().contains(DISPLAY_TAG);
    }

    /** Removes every timber display among the entities; returns how many were removed. */
    static int cleanup(Iterable<? extends Entity> entities) {
        int removed = 0;
        for (Entity entity : entities) {
            if (!isTimberDisplay(entity)) continue;
            entity.remove();
            removed++;
        }
        return removed;
    }
}
